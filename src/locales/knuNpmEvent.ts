export function createEventTranslator(getLocale: () => EventLocale) {
  return (key: string, params?: Record<string, string | number>): string => {
    const loc = getLocale();
    let template = KNU_NPM_TRANSLATIONS[loc]?.[key] ?? KNU_NPM_TRANSLATIONS.en[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        template = template.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      }
    }
    return template;
  };
}
